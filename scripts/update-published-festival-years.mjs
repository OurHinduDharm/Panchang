// Derive the year index from fully approved legacy monthly catalogues.
// New hybrid years require an approved runtime reader before inclusion.
import {readdir,readFile,writeFile} from "node:fs/promises";
import {fileURLToPath,pathToFileURL} from "node:url";
import {join} from "node:path";
export function isPublishedMonth(data,year,month){
  if(data?.year!==year||data.month!==month||data.status!=="approved"||!Array.isArray(data.events)||!data.events.length)return false;
  const prefix=year+"-"+String(month).padStart(2,"0")+"-";
  return data.events.every(event=>{
    if(event?.reviewStatus!=="approved"||typeof event.title!=="string"||!event.title.trim()||typeof event.description!=="string"||!event.description.trim()||typeof event.date!=="string"||!event.date.startsWith(prefix)||!/^\d{4}-\d{2}-\d{2}$/.test(event.date))return false;
    const instant=new Date(event.date+"T00:00:00Z");
    return Number.isFinite(instant.getTime())&&instant.toISOString().slice(0,10)===event.date;
  });
}
export async function discoverPublishedYears(dir){
  const filenames=await readdir(dir);
  const years=[...new Set(filenames.filter(name=>/^\d{4}-\d{2}\.json$/.test(name)).map(name=>Number(name.slice(0,4))))].filter(y=>y>=1900&&y<=2200).sort((a,b)=>a-b);
  const complete=[];
  for(const year of years){
    let valid=true;
    for(let month=1;month<=12;month++){
      try{
        const data=JSON.parse(await readFile(join(dir,year+"-"+String(month).padStart(2,"0")+".json"),"utf8"));
        if(!isPublishedMonth(data,year,month)){valid=false;break;}
      }catch(error){if(error.code==="ENOENT"||error instanceof SyntaxError){valid=false;break;}throw error;}
    }
    if(valid)complete.push(year);
  }
  return complete;
}
export const renderIndex=years=>"// Generated by scripts/update-published-festival-years.mjs; do not hand-edit.\nexport const publishedYears = Object.freeze("+JSON.stringify(years)+");\n";
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  const dir=fileURLToPath(new URL("../data/festivals/",import.meta.url));
  const years=await discoverPublishedYears(dir);
  if(!years.length)throw new Error("No complete approved festival years");
  const file=join(dir,"published-years.mjs"),expected=renderIndex(years);
  if(process.argv.includes("--write"))await writeFile(file,expected);
  else if(await readFile(file,"utf8")!==expected)throw new Error("Published year index stale. Run node scripts/update-published-festival-years.mjs --write and review before publication.");
  console.log("Published festival years:",years.join(", "));
}
