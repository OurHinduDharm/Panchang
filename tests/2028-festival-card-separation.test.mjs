test("2028 independent observances are separate cards with event-specific descriptions", () => {
  for (const [m,date,title] of required) {
    const event = find(m,date,title);
    assert.ok(event, date + " " + title);
    assert.ok((event.description || "").length > 30, date + " description");
    assert.ok(!/के अवसर पर परंपरानुसार पूजा|परंपरानुसार पूजा, व्रत और दान/.test(event.description || ""), date + " generic description");
  }
});

test("2028 has no duplicate same-date cards or placeholder descriptions", () => {
  const seen = new Set();
  for (let m = 1; m <= 12; m++) {
    for (const event of month(m).events) {
      const key = event.date + "|" + event.title;
      assert.ok(!seen.has(key), "duplicate card: " + key);
      seen.add(key);
      assert.ok(!/के अवसर पर परंपरानुसार पूजा|परंपरानुसार पूजा, व्रत और दान/.test(event.description || ""), "generic description: " + key);
    }
  }
});

test("2028 omits non-deity human jayanti entries and obscure Tamil observances", () => {
  const events = Array.from({length:12}, (_,i) => month(i+1)).flatMap(data => data.events);
  assert.equal(events.some(e => /तैलंग स्वामी|टेलंग स्वामी|शबरी जयंती|आदि शंकराचार्य जयंती|नारद जयंती|गुरु गोबिन्द सिंह जयंती|महाराजा अग्रसेन|शिवाजी महाराज|वाल्मीकि जयंती|मीराबाई जयंती|माध्वाचार्य जयंती|अटला तद्दे/.test(e.title || "")), false);
});
